export function ProfessionalPromptEngineeringExercise() {
  const [copiedPrompt, setCopiedPrompt] = useState("");

  async function copyPrompt(prompt: PromptTemplate) {
    try {
      await navigator.clipboard.writeText(prompt.text);
    } catch {
      const textarea = document.createElement("textarea");
      textarea.value = prompt.text;
      document.body.appendChild(textarea);
      textarea.select();
      document.execCommand("copy");
      textarea.remove();
    }

    setCopiedPrompt(prompt.title);
  }

  return (
    <div className="professional-prompts-layout">
      <section className="comparison-intro-card">
        <div className="section-kicker">هندسة الأوامر الاحترافية</div>
        <h2>أنشئ مشروع هندسة أوامر احترافية وفق أطر الدورة</h2>
        <p>
          اختر الصيغة المناسبة، ثم انسخ الأمر كاملاً وضعه في نموذج الذكاء
          الاصطناعي مع ملف القوالب المرجعي عند الحاجة. الصيغة الأولى مناسبة
          لبناء مشروع مضبوط على مراحل، والثانية مناسبة للحصول على تعليمات مشروع
          مباشرة من أول رد.
        </p>
      </section>

      <section className="professional-prompt-list" aria-label="أوامر التمرين">
        {promptTemplates.map((prompt) => (
          <article className="professional-prompt-card" key={prompt.title}>
            <div className="comparison-prompt-head">
              <div>
                <div className="section-kicker">{prompt.source}</div>
                <h3>{prompt.title}</h3>
                <p>{prompt.subtitle}</p>
              </div>
              <button
                type="button"
                className="copy-prompt-button"
                onClick={() => copyPrompt(prompt)}
                aria-label={`نسخ ${prompt.title}`}
                title={`نسخ ${prompt.title}`}
              >
                <CopyIcon />
                <span>نسخ الأمر</span>
              </button>
            </div>

            <label className="professional-prompt-field">
              <span>{prompt.title}</span>
              <textarea
                dir="rtl"
                readOnly
                rows={prompt.rows}
                value={prompt.text}
                spellCheck={false}
              />
            </label>
          </article>
        ))}
      </section>

      <div className="professional-copy-status" aria-live="polite">
        {copiedPrompt ? `تم نسخ ${copiedPrompt}.` : ""}
      </div>
    </div>
  );
}
